"""Formula and source-code exports for 3D Fourier curves."""

from typing import List

from .fourier3d import Epicycle3D


def _n(value: float, precision: int = 4) -> str:
    if abs(value) < 1e-9:
        return "0"
    return f"{value:.{precision}f}".rstrip("0").rstrip(".")


def cartesian_formulas(epicycles: List[Epicycle3D]) -> List[str]:
    result = []
    for axis, name in enumerate(("x", "y", "z")):
        terms = []
        for ep in epicycles:
            real = float(ep.coeff[axis].real)
            imag = float(ep.coeff[axis].imag)
            if ep.freq == 0:
                terms.append(_n(real))
                continue
            angle = f"2π·{ep.freq}·t"
            terms.append(
                f"{_n(real)}·cos({angle}) - {_n(imag)}·sin({angle})"
            )
        result.append(f"{name}(t) = " + (" + ".join(terms) if terms else "0"))
    return result


def complex_vector_formula(epicycles: List[Epicycle3D]) -> str:
    terms = []
    for ep in epicycles:
        vector = ", ".join(
            f"{_n(float(c.real))}{'+' if c.imag >= 0 else '-'}{_n(abs(float(c.imag)))}i"
            for c in ep.coeff
        )
        terms.append(f"([{vector}]) · e^(i·2π·{ep.freq}·t)")
    return "r(t) = Re(Σ cₖ·e^(i·2πkt)), cₖ ∈ ℂ³\n\n" + (
        "\n+ ".join(terms) if terms else "r(t) = (0, 0, 0)"
    )


def latex_formula(epicycles: List[Epicycle3D], max_terms: int = 12) -> str:
    lines = []
    for equation in cartesian_formulas(epicycles):
        lines.append(equation.replace("π", r"\pi").replace("·", r"\,").replace("cos", r"\cos").replace("sin", r"\sin"))
    if len(epicycles) > max_terms:
        lines = [f"{axis}(t) &= \\mathrm{{Re}}\\left(\\sum_k c_{{{axis},k}} e^{{i2\\pi kt}}\\right)" for axis in "xyz"]
    return "\\begin{aligned}\n" + " \\\\\n".join(line.replace(" = ", " &= ") for line in lines) + "\n\\end{aligned}"


def python_code(epicycles: List[Epicycle3D]) -> str:
    rows = [
        f"    ({ep.freq}, {ep.coeff[0].real:.12g}, {ep.coeff[0].imag:.12g}, "
        f"{ep.coeff[1].real:.12g}, {ep.coeff[1].imag:.12g}, "
        f"{ep.coeff[2].real:.12g}, {ep.coeff[2].imag:.12g}),"
        for ep in epicycles
    ]
    return "\n".join([
        '"""3D Fourier curve generated by FourierSplineStudio3D."""',
        "import math",
        "import numpy as np",
        "",
        "# (frequency, Re(cx), Im(cx), Re(cy), Im(cy), Re(cz), Im(cz))",
        "COEFFICIENTS = [",
        *rows,
        "]",
        "",
        "def curve_point(t):",
        "    point = np.zeros(3, dtype=float)",
        "    for k, *values in COEFFICIENTS:",
        "        phase = 2.0 * math.pi * k * t",
        "        c, s = math.cos(phase), math.sin(phase)",
        "        for axis in range(3):",
        "            real, imag = values[2 * axis:2 * axis + 2]",
        "            point[axis] += real * c - imag * s",
        "    return point",
        "",
        "def sample_curve(num_points=1000):",
        "    return np.array([curve_point(t) for t in np.linspace(0.0, 1.0, num_points)])",
        "",
        'if __name__ == "__main__":',
        "    points = sample_curve()",
        "    try:",
        "        import matplotlib.pyplot as plt",
        "        ax = plt.figure().add_subplot(111, projection='3d')",
        "        ax.plot(points[:, 0], points[:, 1], points[:, 2])",
        "        plt.show()",
        "    except ImportError:",
        "        print(points[0])",
    ])


def desmos_syntax(epicycles: List[Epicycle3D]) -> str:
    coordinates = []
    for axis in range(3):
        terms = []
        for ep in epicycles:
            real = float(ep.coeff[axis].real)
            imag = float(ep.coeff[axis].imag)
            if ep.freq == 0:
                terms.append(_n(real))
            else:
                angle = f"2*pi*{ep.freq}*t"
                terms.append(f"{_n(real)}*cos({angle}) - {_n(imag)}*sin({angle})")
        coordinates.append(" + ".join(terms) if terms else "0")
    return "(" + ", ".join(coordinates) + ")"


def javascript_code(epicycles: List[Epicycle3D]) -> str:
    rows = ",\n".join(
        "[" + ", ".join(
            str(v) for v in (
                ep.freq,
                ep.coeff[0].real, ep.coeff[0].imag,
                ep.coeff[1].real, ep.coeff[1].imag,
                ep.coeff[2].real, ep.coeff[2].imag,
            )
        ) + "]"
        for ep in epicycles
    )
    return "\n".join([
        "const coefficients = [",
        rows,
        "];",
        "function curvePoint(t) {",
        "  const p = [0, 0, 0];",
        "  for (const [k, ...c] of coefficients) {",
        "    const a = 2 * Math.PI * k * t, co = Math.cos(a), si = Math.sin(a);",
        "    for (let j = 0; j < 3; j++) p[j] += c[2*j] * co - c[2*j+1] * si;",
        "  }",
        "  return p;",
        "}",
    ])
